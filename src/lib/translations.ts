export type Language = keyof typeof translations;

export const getTranslator = (lang: Language) => {
  // Fallback to English if the selected language is not fully translated
  const translationsForLang = translations[lang] || translations.en;
  const t = (key: keyof typeof translations.en, options?: { context?: string }) => {
    let translationKey = key;
    if (options?.context) {
      const contextualKey = `${key}_${options.context}` as keyof typeof translations.en;
      if (contextualKey in translationsForLang) {
        translationKey = contextualKey;
      }
    }
    return (translationsForLang as any)[translationKey] || translations.en[translationKey] || key;
  };
  return t;
};

    

    