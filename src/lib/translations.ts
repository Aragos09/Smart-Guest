export const getTranslator = (lang: Language) => {
  const translationsForLang = translations[lang] || translations.en;

  const t = (key: string, options?: { context?: string }): string => {
    let translationKey = key;
    
    // Check for contextual translation
    if (options?.context) {
      const contextualKey = `${key}_${options.context}`;
      if ((translationsForLang as any)[contextualKey]) {
        translationKey = contextualKey;
      }
    }
    
    // Check if it's a menu item key
    const menuItemKey = (menuItemTranslations as any)[key];
    if (menuItemKey) {
      return (translationsForLang as any)[menuItemKey] || (translations.en as any)[menuItemKey] || key;
    }
    
    return (translationsForLang as any)[translationKey] || (translations.en as any)[translationKey] || key;
  };
  
  return t;
};
